// tokens.json (base + theme) → themes/<theme>/tokens.css. The JSON is the single source of truth.
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { hexToRgb, luminance } from './lib/color.mjs';
import { loadBase, loadTheme, LAYERS, DESIGN } from './lib/palettes.mjs';

const themeName = process.argv[2] ?? 'canary';
const base = loadBase();
const theme = loadTheme(themeName);
const color = { ...base.color, ...theme.ground };
const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();

// Fluid sizes interpolate between the 390 px and 1440 px viewports.
function size(v) {
  if (!Array.isArray(v)) return `${v}px`;
  const [min, max] = v;
  const slope = (max - min) / (1440 - 390);
  const intercept = min - slope * 390;
  return `clamp(${min}px, ${intercept.toFixed(2)}px + ${(slope * 100).toFixed(3)}vw, ${max}px)`;
}

const lines = [];
const v = (name, value) => lines.push(`  --${name}: ${value};`);

for (const k of ['ground', 'surface', 'raised', 'ink', 'ink2', 'ink3', 'accent', 'loss', 'link']) v(kebab(k).replace(/(\D)(\d)$/, '$1-$2'), color[k]);
v('hairline', `rgb(${hexToRgb(color.ink).join(' ')} / ${base.color.hairlineAlpha})`);
for (const l of LAYERS) v(`strata-${kebab(l)}`, theme.ramp[l]);

v('font-sans', base.font.sans.map((f) => (f.includes(' ') ? `"${f}"` : f)).join(', '));
v('font-mono', base.font.mono.map((f) => (f.includes(' ') ? `"${f}"` : f)).join(', '));
for (const [role, t] of Object.entries(base.type)) {
  v(`type-${role}-family`, `var(--font-${t.family})`);
  v(`type-${role}-size`, size(t.size));
  v(`type-${role}-weight`, t.weight);
  v(`type-${role}-leading`, t.lineHeight);
  v(`type-${role}-tracking`, `${t.tracking}em`);
}
for (const [k, n] of Object.entries(base.space)) v(`space-${k}`, `${n}px`);
for (const [k, n] of Object.entries(base.radius)) v(`radius-${k}`, `${n}px`);
for (const [k, n] of Object.entries(base.line)) v(`line-${k}`, `${n}px`);
v('max-content', `${base.layout.maxContent}px`);
v('measure', base.layout.measure);
v('gutter', `${base.layout.gutter}px`);
v('columns', base.layout.columns);
for (const [k, n] of Object.entries(base.motion.duration)) v(`duration-${k}`, `${n}ms`);
for (const [k, e] of Object.entries(base.motion.ease)) v(`ease-${kebab(k)}`, e);
for (const [k, n] of Object.entries(base.motion.stagger)) v(`stagger-${k}`, `${n}ms`);
v('seam-notch', `${theme.device.notch}px`);
v('seam-notch-every', `${theme.device.notchEvery}px`);

const scheme = luminance(color.ground) < 0.2 ? 'dark' : 'light';
// Font files live in identity/; tokens.css sits two levels below design/.
const faces = Object.entries(base.font.files).map(([family, f]) => `@font-face {
  font-family: "${family}";
  src: url("../../identity/${f.src}") format("woff2");
  font-weight: ${f.weight};
  font-style: normal;
  font-display: swap;
}`).join('\n');
const css = `/* Generated by design/scripts/build-tokens.mjs from identity/base.tokens.json + themes/${themeName}/tokens.json. Do not edit. */
${faces}
:root {
  color-scheme: ${scheme};
${lines.join('\n')}
}
`;
const out = join(DESIGN, 'themes', themeName, 'tokens.css');
writeFileSync(out, css);
console.log(`wrote ${out} (${lines.length} variables, color-scheme ${scheme})`);
