// Contrast checks for every D2 palette. Writes d2/contrast.json and d2/contrast.md.
// Exit 1 if the palette named by --require (default B) fails a required check.
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { contrast, over } from './lib/color.mjs';
import { loadPalettes, LAYERS, DESIGN } from './lib/palettes.mjs';

const TEXT = 4.5, NONTEXT = 3, ADJACENT = 1.15;
const requireId = process.argv.includes('--require') ? process.argv[process.argv.indexOf('--require') + 1] : 'B';

function check(p) {
  const c = p.color;
  const rows = [];
  const add = (kind, name, fg, bg, min, required = true) => {
    const ratio = contrast(fg, bg);
    rows.push({ kind, name, fg, bg, ratio: +ratio.toFixed(2), min, pass: ratio >= min, required });
  };

  for (const [fg, bg] of [['ink', 'ground'], ['ink', 'surface'], ['ink2', 'ground'], ['ink2', 'surface'],
    ['accent', 'ground'], ['accent', 'surface'], ['loss', 'ground'], ['loss', 'surface'], ['link', 'ground']]) {
    add('text', `${fg} on ${bg}`, c[fg], c[bg], TEXT);
  }
  for (const fg of ['accent', 'loss', 'ink3']) add('non-text', `${fg} marker on ground`, c[fg], c.ground, NONTEXT);
  add('non-text', 'hairline on ground (decorative)', over(c.ink, c.hairlineAlpha, c.ground), c.ground, NONTEXT, false);

  // Labels inside a layer use whichever of ink/ground reads better.
  for (const l of LAYERS) {
    const bg = p.ramp[l];
    const best = contrast(c.ink, bg) >= contrast(c.ground, bg) ? 'ink' : 'ground';
    add('layer label', `${best} label on ${l}`, c[best], bg, TEXT);
  }
  // Markers carry a ground-coloured halo, so marker-on-layer is advisory only.
  for (const l of LAYERS) for (const m of ['accent', 'loss']) {
    add('marker on layer (advisory)', `${m} on ${l}`, c[m], p.ramp[l], NONTEXT, false);
  }
  const seq = ['ground', ...LAYERS];
  const col = (k) => (k === 'ground' ? c.ground : p.ramp[k]);
  for (let i = 1; i < seq.length; i++) {
    add('adjacent layers', `${seq[i - 1]} | ${seq[i]}`, col(seq[i]), col(seq[i - 1]), ADJACENT, false);
  }
  const failed = rows.filter((r) => r.required && !r.pass);
  const needHairline = rows.filter((r) => r.kind === 'adjacent layers' && !r.pass).map((r) => r.name);
  return { id: p.id, label: p.label, pass: failed.length === 0, failed: failed.map((r) => r.name), needHairline, rows };
}

const results = loadPalettes().map(check);
writeFileSync(join(DESIGN, 'd2', 'contrast.json'), JSON.stringify(results, null, 2));

const md = ['# D2 contrast report', '', 'Generated by `node scripts/contrast.mjs`. WCAG 2.x ratios. Required: text ≥ 4.5, markers ≥ 3. Adjacent layers below 1.15 get a 1 px hairline (ink at 20%).', ''];
for (const r of results) {
  md.push(`## ${r.label}`, '', `**${r.pass ? 'PASS' : 'FAIL'}**${r.failed.length ? ` (failed: ${r.failed.join(', ')})` : ''}. Hairline needed between: ${r.needHairline.join(', ') || 'none'}.`, '');
  md.push('| check | pair | ratio | min | result |', '|---|---|---|---|---|');
  for (const row of r.rows) md.push(`| ${row.kind} | ${row.name} | ${row.ratio} | ${row.min} | ${row.pass ? 'pass' : row.required ? '**FAIL**' : 'below (advisory)'} |`);
  md.push('');
}
writeFileSync(join(DESIGN, 'd2', 'contrast.md'), md.join('\n'));

for (const r of results) console.log(`${r.id}: ${r.pass ? 'PASS' : 'FAIL ' + r.failed.join(', ')} | hairline: ${r.needHairline.join(', ') || 'none'}`);
const req = results.find((r) => r.id === requireId);
process.exit(req && req.pass ? 0 : 1);
