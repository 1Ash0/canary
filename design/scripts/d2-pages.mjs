import { loadPalettes, loadBase, LAYERS, DESIGN } from './lib/palettes.mjs';

const D2 = join(DESIGN, 'd2');
const base = loadBase();
const nf = new Intl.NumberFormat('en-US');
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const FONTS = 'https://fonts.googleapis.com/css2?family=Instrument+Sans:wght@400;500;600&family=JetBrains+Mono:wght@400;500&family=IBM+Plex+Sans:wght@400;500;600&family=IBM+Plex+Mono:wght@400;500&display=swap';

// ---------- sample run (seeded, synthetic) ----------
function mulberry32(seed) {
  return () => {
    seed = (seed + 0x6d2b79f5) | 0;
    let t = Math.imul(seed ^ (seed >>> 15), 1 | seed);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function buildSample() {
  const rnd = mulberry32(1);
  const between = (a, b) => Math.round(a + rnd() * (b - a));
  const AT = 31, N = 40;
  const steps = [];
  let history = 600, toolOutput = 0, summary = 0;
  for (let i = 1; i <= N; i++) {
    if (i === AT + 1) { summary = 4200; history = 1400; toolOutput = 0; }
    else if (i > 1) {
      history += between(500, 1300);
      if (rnd() < 0.55) toolOutput += between(800, 2600);
    }
    steps.push({ i, layers: { system: 2400, tools: 3800, history, toolOutput, summary } });
  }
  const total = (s) => LAYERS.reduce((a, l) => a + s.layers[l], 0);
  const limit = Math.ceil(total(steps[AT - 1]) / 1000) * 1000 + 1000;
  return {
    meta: { label: 'synthetic fixture', seed: 1, model: null, policy: 'llm_summary', limit_tokens: limit,
      note: 'D2 colour-test sample generated by design/scripts/d2-pages.mjs. Not a run. Not a result.' },
    steps,
    compaction: { at_step: AT, after: steps[AT].layers },
    canaries: [
      { id: 'C1', type: 'constraint', planted_step: 3, text: 'never call delete_branch on main', fate: 'kept', after_text: null },
      { id: 'C2', type: 'identifier', planted_step: 9, text: 'deploy target: eu-west-3b', fate: 'changed', after_text: 'deploy target: EU region' },
      { id: 'C3', type: 'failed_approach', planted_step: 14, text: 'retrying with --force corrupted the cache', fate: 'gone', after_text: null },
    ],
  };
}

// ---------- strata frame (SVG, 1080x1350) ----------
const ORDER = ['system', 'tools', 'summary', 'history', 'toolOutput'];
const LABEL = { system: 'system', tools: 'tools', history: 'history', toolOutput: 'tool output', summary: 'summary' };

function strataSvg(p, run) {
  const c = p.color, W = 1080, H = 1350, M = 64;
  const top = 150, x0 = 120, limitX = 720, labelX = 752;
  const AT = run.compaction.at_step, gap = 28, pitch = 22, bar = 15;
  const scale = (limitX - x0) / run.meta.limit_tokens;
  const rowY = (i) => top + (i - 1) * pitch + (i > AT ? gap : 0);
  const out = [];
  const t = (x, y, s, { size = 13, fill = c.ink2, family = 'mono', weight = 400, anchor = 'start' } = {}) =>
    out.push(`<text x="${x}" y="${y}" font-family="var(--${family})" font-size="${size}" font-weight="${weight}" fill="${fill}" text-anchor="${anchor}">${esc(s)}</text>`);

  out.push(`<rect width="${W}" height="${H}" fill="${c.ground}"/>`);
  // status strip
  const last = run.steps[run.steps.length - 1];
  const lastTotal = LAYERS.reduce((a, l) => a + last.layers[l], 0);
  t(M, 92, 'canary', { size: 24, fill: c.ink, family: 'sans', weight: 600 });
  t(M + 104, 92, `run_synthetic_001 · ${run.meta.policy}`, { size: 14 });
  // instrument readouts: small label over value, right-aligned columns
  const readouts = [['data', 'synthetic fixture'], ['tokens', `${nf.format(lastTotal)} / ${nf.format(run.meta.limit_tokens)}`], ['step', `${last.i} / ${run.steps.length}`]];
  let rx = W - M;
  for (const [label, value] of readouts) {
    t(rx, 70, label, { size: 11, anchor: 'end' });
    t(rx, 93, value, { size: 15, fill: c.ink, anchor: 'end', weight: 500 });
    rx -= value.length * 9 + 40;
  }
  out.push(`<line x1="${M}" y1="112" x2="${W - M}" y2="112" stroke="${c.ink}" stroke-opacity="0.2"/>`);

  // limit rule
  out.push(`<line x1="${limitX}" y1="${top - 14}" x2="${limitX}" y2="${rowY(run.steps.length) + bar + 6}" stroke="${c.ink3}" stroke-width="1"/>`);
  t(limitX, top - 20, `limit ${nf.format(run.meta.limit_tokens)}`, { size: 12, anchor: 'end' });

  // bars
  for (const s of run.steps) {
    const y = rowY(s.i);
    let x = x0;
    for (const l of ORDER) {
      const w = s.layers[l] * scale;
      if (w > 0) out.push(`<rect x="${x.toFixed(1)}" y="${y}" width="${Math.max(0, w - 1).toFixed(1)}" height="${bar}" fill="${p.ramp[l]}"/>`);
      x += w;
    }
    if (s.i === 1 || s.i % 5 === 0 || s.i === AT) t(x0 - 14, y + 13, String(s.i), { size: 12, anchor: 'end', fill: s.i === AT ? c.ink : c.ink2 });
  }

  // compaction seam: 1px ink rule, notch ticks, mono label
  const seamY = rowY(AT) + bar + gap / 2 + 2;
  out.push(`<line x1="${M}" y1="${seamY}" x2="${W - M}" y2="${seamY}" stroke="${c.ink}" stroke-width="1"/>`);
  for (let x = M; x <= W - M; x += 48) out.push(`<line x1="${x}" y1="${seamY - 6}" x2="${x}" y2="${seamY}" stroke="${c.ink}" stroke-width="1"/>`);
  t(W - M, seamY - 10, `compaction @ step ${AT}`, { size: 13, fill: c.ink, anchor: 'end' });

  // canaries: plant position = end of history at the planted step
  const histStart = (s) => x0 + (s.layers.system + s.layers.tools + s.layers.summary) * scale;
  const marker = (x, y, fate) => {
    const halo = `<circle cx="${x}" cy="${y}" r="9" fill="${c.ground}"/>`;
    if (fate === 'gone') return halo + `<circle cx="${x}" cy="${y}" r="6" fill="${c.loss}"/>`;
    if (fate === 'changed') return halo + `<circle cx="${x}" cy="${y}" r="5.5" fill="none" stroke="${c.accent}" stroke-width="2" stroke-dasharray="3 2.2"/>`;
    return halo + `<circle cx="${x}" cy="${y}" r="6" fill="${c.accent}"/>`;
  };
  const after = run.steps[AT];
  const lastBarEnd = rowY(run.steps.length) + bar;
  const axisY = lastBarEnd + 14;
  const sumCenter = x0 + (after.layers.system + after.layers.tools + after.layers.summary / 2) * scale;
  const changedRow = AT + 3;
  run.canaries.forEach((k) => {
    const s = run.steps[k.planted_step - 1];
    const x = histStart(s) + s.layers.history * scale - 4, y = rowY(s.i) + bar / 2;
    out.push(`<line x1="${x}" y1="${y}" x2="${labelX - 8}" y2="${y}" stroke="${c.accent}" stroke-width="1"/>`);
    out.push(marker(x, y, 'kept'));
    t(labelX, y - 2, `${k.id} · ${k.type.replace('_', ' ')} · step ${k.planted_step}`, { size: 12, fill: c.ink });
    t(labelX, y + 15, k.text, { size: 13, fill: c.ink2, family: 'sans' });

    // Fates. A kept or changed fact lives in the summary band from step AT+1 on;
    // a gone fact is not in any post-compaction row, so it drops below the diagram.
    if (k.fate === 'gone') {
      // falls from where the fact sat at the seam
      const sx = x, y0 = seamY + 1, gy = axisY + 40;
      out.push(`<line x1="${sx}" y1="${y0}" x2="${sx}" y2="${gy - 9}" stroke="${c.loss}" stroke-width="1" stroke-dasharray="2 3"/>`);
      out.push(marker(sx, gy, 'gone'));
      out.push(`<line x1="${sx + 10}" y1="${gy}" x2="${labelX - 8}" y2="${gy}" stroke="${c.loss}" stroke-width="1"/>`);
      t(labelX, gy - 2, `${k.id} · gone ↓`, { size: 12, fill: c.loss, weight: 500 });
      t(labelX, gy + 15, 'absent from the summary', { size: 13, fill: c.ink2, family: 'sans' });
    } else {
      const row = k.fate === 'kept' ? AT + 1 : changedRow;
      const sx = sumCenter, fy = rowY(row) + bar / 2;
      out.push(`<line x1="${sx + 10}" y1="${fy}" x2="${labelX - 8}" y2="${fy}" stroke="${c.accent}" stroke-width="1"${k.fate === 'changed' ? ' stroke-dasharray="4 3"' : ''}/>`);
      out.push(marker(sx, fy, k.fate));
      t(labelX, fy - 2, `${k.id} · ${k.fate}`, { size: 12, fill: c.ink, weight: 500 });
      t(labelX, fy + 15, k.fate === 'changed' ? `→ ${k.after_text}` : 'verbatim in summary', { size: 13, fill: c.ink2, family: 'sans' });
    }
  });

  // token axis: hairline with 10k ticks, so bar length is readable
  out.push(`<line x1="${x0}" y1="${axisY}" x2="${limitX}" y2="${axisY}" stroke="${c.ink}" stroke-opacity="0.2"/>`);
  for (let v = 0; v <= run.meta.limit_tokens; v += 10000) {
    const x = x0 + v * scale;
    out.push(`<line x1="${x}" y1="${axisY}" x2="${x}" y2="${axisY + 4}" stroke="${c.ink3}"/>`);
    t(x, axisY + 17, v === 0 ? '0' : `${v / 1000}k`, { size: 11, anchor: 'middle' });
  }

  // legend
  const ly = axisY + 92;
  let lx = x0;
  for (const l of ORDER) {
    out.push(`<rect x="${lx}" y="${ly - 10}" width="12" height="12" fill="${p.ramp[l]}" stroke="${c.ink}" stroke-opacity="0.2"/>`);
    t(lx + 18, ly, LABEL[l], { size: 12 });
    lx += 22 + LABEL[l].length * 8 + 18;
  }

  // caption strip
  out.push(`<line x1="${M}" y1="${H - 156}" x2="${W - M}" y2="${H - 156}" stroke="${c.ink}" stroke-opacity="0.2"/>`);
  t(M, H - 108, '3 facts planted. 1 compaction. 1 kept, 1 changed, 1 gone.', { size: 30, fill: c.ink, family: 'sans', weight: 500 });
  t(M, H - 74, 'all values from design/d2/strata_sample.json · synthetic fixture · not a measured result', { size: 13 });
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}" role="img" aria-label="Strata frame, candidate ${p.id}">${out.join('')}</svg>`;
}

const page = (title, body, extraCss = '') => `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>${esc(title)}</title>
<link rel="stylesheet" href="${FONTS}">
<style>:root{--sans:"Instrument Sans",system-ui,sans-serif;--mono:"JetBrains Mono",ui-monospace,monospace}*{box-sizing:border-box;margin:0}body{font-family:var(--sans)}${extraCss}</style></head><body>${body}</body></html>`;

// ---------- write ----------
const run = buildSample();
writeFileSync(join(D2, 'strata_sample.json'), JSON.stringify(run, null, 2));
